const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path = require('node:path');
const fs = require('node:fs');
const root = path.resolve(__dirname, '..');
const artifacts = path.join(root, '.run');
fs.mkdirSync(artifacts, {recursive:true});
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || '/usr/bin/google-chrome', headless:true, args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  let originalDefaults;
  try {
    await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173');
    originalDefaults = await (await page.request.get(new URL('/api/config', page.url()).href)).json();
    await page.request.patch(new URL('/api/config', page.url()).href, {data:{apply_business_defaults:false}});
    await page.reload();
    await page.getByText('Business defaults are off. Only values found on the invoice are filled.').waitFor();
    await page.locator('input[type=file]').setInputFiles([path.join(root, '66075.pdf'),path.join(root, 'PDF.pdf')]);
    const extractionPromise = page.waitForResponse(r => r.url().endsWith('/api/upload') && r.request().method() === 'POST');
    await page.getByRole('button',{name:'Extract Invoices (2)',exact:true}).click();
    const extracted = (await (await extractionPromise).json()).invoices;
    assert.equal(extracted[0].warehouse_name, '');
    assert.equal(extracted[0].receiver_email, '');
    assert.equal(extracted[0].boxes[0].weight, null);
    assert.equal(extracted[0].boxes[0].quantity, 145);
    assert.equal(extracted[1].receiver_mobile, '');
    assert.doesNotMatch(extracted[1].receiver_address, /Bank|Taxable|HDFC/);
    await page.locator('tbody tr').first().click();
    await page.getByRole('button',{name:'Add Box',exact:true}).click();
    assert.equal(await page.getByPlaceholder('Weight (kg)',{exact:true}).last().inputValue(),'');
    assert.equal(await page.getByPlaceholder('Quantity',{exact:true}).last().inputValue(),'');
    await page.getByRole('button',{name:'Cancel',exact:true}).click();
    await page.getByRole('button',{name:'GENERATE EXCEL',exact:true}).click();
    await page.getByRole('link',{name:'Download Excel',exact:true}).waitFor();
    const strictDownload = page.waitForEvent('download');
    await page.getByRole('link',{name:'Download Excel',exact:true}).click();
    await (await strictDownload).saveAs(path.join(artifacts,'browser-extracted-only.xlsx'));
    await page.getByRole('button',{name:'New Batch',exact:true}).click();
    const defaults = page.getByRole('button', {name:'Defaults', exact:true});
    await defaults.click();
    await page.getByRole('checkbox', {name:'Use business defaults for missing fields'}).check();
    await page.getByText('Warehouse Name', {exact:true}).locator('..').locator('input').fill('Browser Test Warehouse');
    const weight = page.getByText('Weight (kg)', {exact:true}).locator('..').locator('input');
    await weight.fill('-1');
    await page.getByRole('button',{name:'Save Defaults',exact:true}).click();
    await page.getByRole('alert').waitFor();
    assert.match(await page.getByRole('alert').innerText(), /greater than 0/);
    await weight.fill('7');
    await page.getByRole('button',{name:'Save Defaults',exact:true}).click();
    await page.getByText('Configurable Business Defaults').waitFor({state:'hidden'});
    await page.locator('input[type=file]').setInputFiles([path.join(root, '66075.pdf'),path.join(root, 'PDF.pdf')]);
    await page.getByRole('button',{name:'Extract Invoices (2)',exact:true}).click();
    await page.getByRole('heading',{name:'Extracted Invoices (2)',exact:true}).waitFor({timeout:30000});
    await page.getByRole('button',{name:'GENERATE EXCEL',exact:true}).click();
    await page.getByRole('link',{name:'Download Excel',exact:true}).waitFor();
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('link',{name:'Download Excel',exact:true}).click();
    const download = await downloadPromise;
    await download.saveAs(path.join(artifacts, 'browser-export.xlsx'));
    await page.locator('tbody tr').first().click();
    const warehouse = page.getByText('Warehouse Name',{exact:true}).locator('..').locator('input');
    assert.equal(await warehouse.inputValue(),'Browser Test Warehouse');
    await warehouse.fill('Edited Warehouse');
    await page.getByRole('button',{name:'Add Box',exact:true}).click();
    assert.equal(await page.getByPlaceholder('Weight (kg)',{exact:true}).last().inputValue(),'7');
    await page.getByRole('button',{name:'Save Changes',exact:true}).click();
    await page.getByRole('button',{name:'Save Changes',exact:true}).waitFor({state:'hidden'});
    assert.equal(await page.getByRole('link',{name:'Download Excel',exact:true}).count(),0);
    await page.getByRole('button',{name:'GENERATE EXCEL',exact:true}).click();
    await page.getByRole('link',{name:'Download Excel',exact:true}).waitFor();
    const updatedPromise = page.waitForEvent('download');
    await page.getByRole('link',{name:'Download Excel',exact:true}).click();
    await (await updatedPromise).saveAs(path.join(artifacts, 'browser-export-updated.xlsx'));
    await page.screenshot({path:path.join(artifacts, 'invoice-app.png'),fullPage:true});
    await page.reload();
    await page.getByRole('button', {name:'Batch history', exact:true}).click();
    await page.getByRole('heading', {name:'Recent batches', exact:true}).waitFor();
    await page.getByRole('button', {name:/66075\.pdf/}).first().click();
    await page.getByRole('heading', {name:'Extracted Invoices (2)', exact:true}).waitFor();
    await page.locator('tbody tr').first().click();
    assert.equal(await page.getByText('Warehouse Name',{exact:true}).locator('..').locator('input').inputValue(), 'Edited Warehouse');
    assert.deepEqual(errors,[]);
    console.log('PASS: blank missing fields, no seller-column contamination, explicit defaults, edit, regeneration, and download; no browser errors.');
  } finally {
    if (originalDefaults) await page.request.patch(new URL('/api/config', page.url()).href, {data:originalDefaults});
    await browser.close();
  }
})().catch(e=>{console.error(e);process.exitCode=1;});
